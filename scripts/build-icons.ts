/**
 * Builds src/components/icon-data.ts from the Solar icon set.
 * The old PHP pages loaded every icon at runtime from a CDN. This bundles only the ones used,
 * so there is no extra request and no flash of missing icons.
 *
 * Add a name to NAMES, then run `npm run icons`.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const set = JSON.parse(readFileSync(require.resolve("@iconify-json/solar/icons.json"), "utf8")) as {
  icons: Record<string, { body: string }>;
  aliases?: Record<string, { parent: string }>;
  width?: number;
  height?: number;
};

/** Names the pages use that the current Solar release calls something else. */
const RENAMED: Record<string, string> = { "trending-up-linear": "graph-up-linear" };

const NAMES = [
  "book-2-linear",
  "book-linear",
  "book-bold",
  "box-linear",
  "magnifer-linear",
  "letter-linear",
  "users-group-rounded-linear",
  "user-linear",
  "user-circle-linear",
  "trending-up-linear",
  "phone-linear",
  "info-circle-linear",
  "check-circle-linear",
  "check-circle-bold",
  "arrow-left-linear",
  "alt-arrow-left-linear",
  "alt-arrow-right-linear",
  "alt-arrow-down-linear",
  "trash-bin-trash-linear",
  "shield-user-linear",
  "shield-check-linear",
  "pen-linear",
  "logout-2-linear",
  "diskette-linear",
  "cart-plus-linear",
  "cart-large-linear",
  "card-linear",
  "bag-3-linear",
  "add-circle-linear",
  "add-linear",
  "minus-linear",
  "minus-circle-linear",
  "widget-linear",
  "sort-linear",
  "eye-linear",
  "dollar-linear",
  "document-text-linear",
  "delivery-linear",
  "chat-line-linear",
  "lock-password-linear",
  "danger-triangle-linear",
  "close-circle-linear",
];

const lines: string[] = [];
const missing: string[] = [];
for (const name of NAMES) {
  const target = RENAMED[name] ?? name;
  const icon = set.icons[target] ?? (set.aliases?.[target] ? set.icons[set.aliases[target].parent] : undefined);
  if (!icon) {
    missing.push(name);
    continue;
  }
  lines.push(`  ${JSON.stringify(name)}: ${JSON.stringify(icon.body)},`);
}
if (missing.length) {
  console.error("Missing from the Solar set:", missing.join(", "));
  process.exit(1);
}

writeFileSync(
  "src/components/icon-data.ts",
  `// Generated by scripts/build-icons.ts. Do not edit by hand.\n// Solar icon set by 480 Design, CC BY 4.0. https://icon-sets.iconify.design/solar/\nexport const ICON_VIEWBOX = "0 0 ${set.width ?? 24} ${set.height ?? 24}";\n\nexport const ICONS: Record<string, string> = {\n${lines.join("\n")}\n};\n`,
);
console.log(`Wrote ${lines.length} icons.`);
